class CondicionalIfElse {
    public static void main(String[] args) {
        int edad = 15;

        if (edad >= 18) {
            System.out.println("Mayor de edad");
        } else if (edad >= 13) {
            System.out.println("Adolescente");
        } else {
            System.out.println("Niño");
        }
    }
}
